#!/usr/bin/env python3
"""Keeps Codex and OpenCode in step with the vault: agents, commands, skills and the
memory index, so every coding tool works with the same workflow and knowledge.

Global (no arguments), for each tool that is installed:
  agents    <vault>/agents plus the sets listed in ~/.claude/global-agent-sets
            OpenCode: ~/.config/opencode/agents/<name>.md
            Codex:    ~/.codex/agents/<name>.toml (an agent with its own MCP server is
                      skipped: Codex agents only inherit the session's servers)
  commands  <vault>/commands/*.md
            OpenCode: ~/.config/opencode/commands/<name>.md (same template syntax)
            Codex:    ~/.agents/skills/<name>/SKILL.md (Codex has skills, not commands)
  skills    ~/.claude/skills/<name> linked into ~/.agents/skills for Codex; OpenCode
            reads ~/.claude/skills itself
  memory    OpenCode: <vault>/memory/MEMORY.md in "instructions" of opencode.json;
            Codex gets it from the SessionStart hook session_context.py
  agent-only MCP servers (frontmatter mcpServers) become OpenCode servers that are off
            for every agent but their own

--project <repo>: the links in <repo>/.claude/agents that point into the vault become
.opencode/agents and .codex/agents copies, kept out of git like the links.

Only files carrying OWN are written or removed; anything the user wrote stays.
"""
import json
import os
import re
import subprocess
import sys

HOME = os.path.expanduser("~")
VAULT = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
SETS_FILE = os.path.join(HOME, ".claude", "global-agent-sets")
OPENCODE = os.path.join(HOME, ".config", "opencode")
CODEX = os.path.join(HOME, ".codex")
AGENT_SKILLS = os.path.join(HOME, ".agents", "skills")
CLAUDE_SKILLS = os.path.join(HOME, ".claude", "skills")
STATE = os.path.join(HOME, ".config", "agent-workbench", "opencode-servers.json")
MARKER = "# generated by tool-sync.py from the vault; edit the source in the vault instead"
# Also recognises files written by the earlier opencode-agents.py.
OWN = ("# generated by tool-sync.py", "# generated by opencode-agents.py")

# OpenCode permission keys and the Claude Code tools that grant them.
PERMISSIONS = {
    "read": {"Read"},
    "list": {"Read", "Glob"},
    "glob": {"Glob"},
    "grep": {"Grep"},
    "edit": {"Edit", "Write", "MultiEdit", "NotebookEdit"},
    "bash": {"Bash"},
    "task": {"Agent", "Task"},
    "webfetch": {"WebFetch"},
    "websearch": {"WebSearch"},
}


def log(text):
    print(f"tool-sync: {text}", file=sys.stderr)


def is_own(path):
    try:
        head = open(path, encoding="utf-8").read(400)
    except OSError:
        return False
    return any(marker in head for marker in OWN)


def write(path, text):
    """Writes a generated file unless the user owns one at that path; True when it is ours."""
    if os.path.exists(path) and not is_own(path):
        log(f"{path} is the user's own, left alone")
        return False
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if not os.path.exists(path) or open(path, encoding="utf-8").read() != text:
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
    return True


def parse(text):
    """Frontmatter fields, the agent-only MCP servers and the body of a Claude Code file."""
    match = re.match(r"---\n(.*?)\n---\n?(.*)", text.replace("\r\n", "\n"), re.S)
    if not match:
        return {}, {}, text
    fields, servers, key = {}, {}, None
    for line in match.group(1).splitlines():
        if not line.startswith((" ", "\t")):
            key, sep, value = line.partition(":")
            key = key.strip()
            if sep:
                fields[key] = value.strip()
        elif key == "mcpServers":
            item = re.match(r"\s*-\s*([A-Za-z0-9_.-]+):\s*(\{.*\})\s*$", line)
            if item:
                try:
                    servers[item.group(1)] = json.loads(item.group(2))
                except ValueError:
                    log(f"unreadable mcpServers entry {item.group(1)}")
    return fields, servers, match.group(2)


def unquote(value):
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1].replace('\\"', '"') if value[0] == '"' else value[1:-1].replace("''", "'")
    return value


def tool_list(fields):
    if not fields.get("tools"):
        return None
    return {t.strip() for t in unquote(fields["tools"]).split(",") if t.strip()}


def toml_string(value):
    return json.dumps(value, ensure_ascii=False)


# ------------------------------------------------------------------ renderers

def opencode_agent(text):
    fields, servers, body = parse(text)
    if not fields.get("description"):
        return None
    lines = ["---", MARKER, f"description: {toml_string(unquote(fields['description']))}", "mode: subagent"]
    tools = tool_list(fields)
    if tools is not None:
        lines.append("permission:")
        for key, grants in PERMISSIONS.items():
            lines.append(f"  {key}: {'allow' if tools & grants else 'deny'}")
    if servers:
        lines.append("tools:")
        lines += [f'  "{name}*": true' for name in servers]
    lines.append("---")
    return "\n".join(lines) + "\n" + body


def codex_agent(name, text):
    fields, servers, body = parse(text)
    if not fields.get("description"):
        return None
    if servers:
        log(f"{name}: has its own MCP server, which Codex agents cannot have; skipped for Codex")
        return None
    out = [MARKER, f"name = {toml_string(name)}", f"description = {toml_string(unquote(fields['description']))}",
           f"developer_instructions = {toml_string(body.strip())}"]
    tools = tool_list(fields)
    if tools is not None and "Bash" not in tools:
        out += ["", "[features]", "shell_tool = false"]
    return "\n".join(out) + "\n"


def opencode_command(text):
    fields, _, body = parse(text)
    lines = ["---", MARKER]
    if fields.get("description"):
        lines.append(f"description: {toml_string(unquote(fields['description']))}")
    lines.append("---")
    return "\n".join(lines) + "\n" + body


def codex_command_skill(name, text):
    """A Claude command as a Codex skill: shell injections become instructions to run them."""
    fields, _, body = parse(text)
    description = unquote(fields.get("description", "")) or f"The /{name} command of the vault."
    body = re.sub(r"!`([^`]+)`", r"(run `\1` and use its output here)", body)
    body = body.replace("$ARGUMENTS", "(the text the user wrote after the skill name)")
    if not description.endswith("."):
        description += "."
    head = ["---", MARKER, f"name: {name}", f"description: {toml_string(description + f' Invoke it as ${name}.')}", "---"]
    return "\n".join(head) + "\n" + body


# ------------------------------------------------------------------ sources

def agent_sources():
    folders = [os.path.join(VAULT, "agents")]
    if os.path.isfile(SETS_FILE):
        for line in open(SETS_FILE, encoding="utf-8"):
            name = line.split("#", 1)[0].strip()
            if name:
                folders.append(os.path.join(VAULT, "project-agents", name))
    found = {}
    for folder in folders:
        if os.path.isdir(folder):
            for name in sorted(os.listdir(folder)):
                path = os.path.join(folder, name)
                if name.endswith(".md") and os.path.isfile(path):
                    found.setdefault(name[:-3], path)
    return found


def project_agent_sources(repo):
    folder = os.path.join(repo, ".claude", "agents")
    found = {}
    if os.path.isdir(folder):
        for name in sorted(os.listdir(folder)):
            path = os.path.join(folder, name)
            real = os.path.realpath(path)
            if name.endswith(".md") and os.path.islink(path) and real.startswith(VAULT + os.sep) and os.path.isfile(real):
                found[name[:-3]] = real
    return found


def command_sources():
    folder = os.path.join(VAULT, "commands")
    return {n[:-3]: os.path.join(folder, n) for n in sorted(os.listdir(folder)) if n.endswith(".md")} if os.path.isdir(folder) else {}


# ------------------------------------------------------------------ sync

def sync_files(found, target, ext, render):
    """Renders every source into target/<name><ext>, removes own files that lost their source."""
    wanted = set()
    for name, path in found.items():
        text = render(name, open(path, encoding="utf-8").read())
        if text is not None and write(os.path.join(target, name + ext), text):
            wanted.add(name + ext)
    if os.path.isdir(target):
        for entry in os.listdir(target):
            path = os.path.join(target, entry)
            if entry.endswith(ext) and entry not in wanted and os.path.isfile(path) and is_own(path):
                os.remove(path)
    return wanted


def sync_codex_skills(commands):
    """Command skills and links to Claude Code's skills in ~/.agents/skills."""
    wanted = set()
    for name, path in commands.items():
        if os.path.isdir(os.path.join(CLAUDE_SKILLS, name)):
            log(f"command {name} has the name of a skill; the skill wins in Codex")
            continue
        if write(os.path.join(AGENT_SKILLS, name, "SKILL.md"), codex_command_skill(name, open(path, encoding="utf-8").read())):
            wanted.add(name)
    if os.path.isdir(CLAUDE_SKILLS):
        for name in sorted(os.listdir(CLAUDE_SKILLS)):
            source = os.path.join(CLAUDE_SKILLS, name)
            if not os.path.isfile(os.path.join(source, "SKILL.md")):
                continue
            link = os.path.join(AGENT_SKILLS, name)
            if os.path.islink(link) and os.readlink(link) == source:
                continue
            if os.path.lexists(link):
                log(f"{link} exists, Claude Code's skill {name} not linked")
                continue
            os.makedirs(AGENT_SKILLS, exist_ok=True)
            os.symlink(source, link)
    if os.path.isdir(AGENT_SKILLS):
        for name in os.listdir(AGENT_SKILLS):
            path = os.path.join(AGENT_SKILLS, name)
            if os.path.islink(path):
                if os.readlink(path).startswith(CLAUDE_SKILLS + os.sep) and not os.path.exists(path):
                    os.remove(path)
            elif name not in wanted and is_own(os.path.join(path, "SKILL.md")):
                os.remove(os.path.join(path, "SKILL.md"))
                if not os.listdir(path):
                    os.rmdir(path)


def opencode_server(config):
    """A Claude Code MCP config in OpenCode's shape; ${VAR} becomes {env:VAR}."""
    env = lambda value: re.sub(r"\$\{([A-Za-z_][A-Za-z0-9_]*)\}", r"{env:\1}", str(value))
    if config.get("type", "stdio") == "stdio":
        entry = {"type": "local", "command": [config.get("command", "")] + list(config.get("args", [])), "enabled": True}
        if config.get("env"):
            entry["environment"] = {k: env(v) for k, v in config["env"].items()}
    else:
        entry = {"type": "remote", "url": config.get("url", ""), "enabled": True, "oauth": False}
        if config.get("headers"):
            entry["headers"] = {k: env(v) for k, v in config["headers"].items()}
    return entry


def sync_opencode_config(agents):
    """Memory index in "instructions", agent-only servers in "mcp" with their tools off globally."""
    path = os.path.join(OPENCODE, "opencode.json")
    try:
        data = json.load(open(path, encoding="utf-8")) if os.path.exists(path) else {"$schema": "https://opencode.ai/config.json"}
    except ValueError:
        log("opencode.json has comments (JSONC); memory and agent-only servers not added")
        return
    before = json.dumps(data, sort_keys=True)

    memory = os.path.join(VAULT, "memory", "MEMORY.md")
    instructions = [i for i in data.get("instructions", []) if not i.endswith("/memory/MEMORY.md")]
    if os.path.isfile(memory):
        instructions.append(memory)
    if instructions:
        data["instructions"] = instructions

    servers = {}
    for path_ in agents.values():
        servers.update(parse(open(path_, encoding="utf-8").read())[1])
    managed = json.load(open(STATE)) if os.path.exists(STATE) else []
    mcp, tools = data.setdefault("mcp", {}), data.setdefault("tools", {})
    for name in managed:
        if name not in servers:
            mcp.pop(name, None)
            tools.pop(f"{name}*", None)
    for name, config in servers.items():
        mcp[name] = opencode_server(config)
        tools[f"{name}*"] = False
    for key in ("mcp", "tools"):
        if not data[key]:
            del data[key]

    if json.dumps(data, sort_keys=True) != before:
        with open(path, "w", encoding="utf-8") as fh:
            json.dump(data, fh, indent=2)
        os.chmod(path, 0o600)
    os.makedirs(os.path.dirname(STATE), exist_ok=True)
    json.dump(sorted(servers), open(STATE, "w"))


def exclude(repo, prefix, names):
    try:
        common = subprocess.run(["git", "-C", repo, "rev-parse", "--git-common-dir"],
                                capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return
    path = os.path.join(common if os.path.isabs(common) else os.path.join(repo, common), "info", "exclude")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    lines = open(path, encoding="utf-8").read().splitlines() if os.path.exists(path) else []
    kept = [l for l in lines if not l.startswith(prefix)] + [prefix + n for n in sorted(names)]
    if kept != lines:
        open(path, "w", encoding="utf-8").write("\n".join(kept) + "\n")


def project(repo):
    repo = os.path.realpath(repo)
    found = project_agent_sources(repo)
    if os.path.isdir(OPENCODE):
        target = os.path.join(repo, ".opencode", "agents")
        if found or os.path.isdir(target):
            exclude(repo, "/.opencode/agents/", sync_files(found, target, ".md", lambda n, t: opencode_agent(t)))
    if os.path.isdir(CODEX):
        target = os.path.join(repo, ".codex", "agents")
        if found or os.path.isdir(target):
            exclude(repo, "/.codex/agents/", sync_files(found, target, ".toml", codex_agent))


def main():
    if len(sys.argv) == 3 and sys.argv[1] == "--project":
        project(sys.argv[2])
        return 0
    agents, commands = agent_sources(), command_sources()
    if os.path.isdir(OPENCODE):
        sync_files(agents, os.path.join(OPENCODE, "agents"), ".md", lambda n, t: opencode_agent(t))
        sync_files(commands, os.path.join(OPENCODE, "commands"), ".md", lambda n, t: opencode_command(t))
        sync_opencode_config(agents)
    if os.path.isdir(CODEX):
        sync_files(agents, os.path.join(CODEX, "agents"), ".toml", codex_agent)
        sync_codex_skills(commands)
    return 0


if __name__ == "__main__":
    sys.exit(main())
